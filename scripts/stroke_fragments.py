"""Stroke boundaries on Make Me a Hanzi medians, in component-local stroke order."""
from dataclasses import dataclass


@dataclass(frozen=True)
class Cut:
    axis: int  # 0 for x, 1 for y (upwards)
    stroke: int  # reference median in the same component
    fraction: float  # between that median's minimum and maximum on the axis


@dataclass(frozen=True)
class MiddleBend:
    # Direction along x immediately before the middle zigzag changes direction.
    direction: int


@dataclass(frozen=True)
class Parts:
    owners: tuple
    cuts: tuple


def remap(owner, keys, strokes):
    if isinstance(owner, int):
        return keys.get(owner, -1)
    if isinstance(owner, tuple):
        retained = tuple(dict.fromkeys(keys[k] for k in owner if k in keys))
        return retained if len(retained) > 1 else next(iter(retained), -1)
    return Parts(tuple(remap(k, keys, strokes) for k in owner.owners),
                 tuple(c if isinstance(c, MiddleBend) else Cut(c.axis, strokes[c.stroke], c.fraction)
                       for c in owner.cuts))


def split_stroke(points, cuts, medians):
    pieces = []
    original = points
    for cut in cuts:
        if isinstance(cut, MiddleBend):
            low = min(y for x, y in original)
            span = max(y for x, y in original) - low
            for i in range(1, len(points)-1):
                x, y = points[i]
                if (low + .37*span < y < low + .83*span and
                        (x-points[i-1][0])*cut.direction > 0 and
                        (points[i+1][0]-x)*cut.direction <= 0):
                    pieces.append(points[:i+1])
                    points = points[i:]
                    break
            else:
                return
            continue
        coords = [p[cut.axis] for p in medians[cut.stroke]]
        boundary = min(coords) + (max(coords) - min(coords)) * cut.fraction
        for i, (p, q) in enumerate(zip(points, points[1:])):
            a, b = p[cut.axis], q[cut.axis]
            if a == b or not min(a, b) <= boundary <= max(a, b):
                continue
            t = (boundary - a) / (b - a)
            cross = [round(x + t * (y-x), 1) for x, y in zip(p, q)]
            pieces.append(points[:i+1] + [cross])
            points = [cross] + points[i+1:]
            break
        else:
            return
    return pieces + [points]


def paths_for(owners, glyph):
    if all(isinstance(owner, int) for owner in owners):
        return dict(paths=list(zip(owners, glyph['strokes'])))
    paths = []
    medians = glyph['medians']
    for i, owner in enumerate(owners):
        parts = owner if isinstance(owner, Parts) else Parts((owner,), ())
        segments = split_stroke(medians[i], parts.cuts, medians)
        if segments is None:
            return
        for key, segment in zip(parts.owners, segments, strict=True):
            path = 'M' + ' L'.join(f'{x} {y}' for x, y in segment)
            for root in key if isinstance(key, tuple) else (key,):
                paths.append([root, path])
    return dict(paths=paths, medians=True)


